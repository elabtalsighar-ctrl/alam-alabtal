import { useSEO } from '../lib/seo';

function PolicyPage({ title, sections }: { title: string; sections: { h: string; body: string[] }[] }) {
  useSEO({ title: `${title} | عالم الأبطال الصغار` });
  return (
    <div className="container-px max-w-3xl py-12">
      <h1 className="mb-8 text-3xl font-extrabold text-slate-900">{title}</h1>
      <div className="space-y-6">
        {sections.map((s, i) => (
          <section key={i}>
            <h2 className="mb-2 text-xl font-extrabold text-slate-800">{s.h}</h2>
            {s.body.map((p, j) => <p key={j} className="mb-2 leading-relaxed text-slate-600">{p}</p>)}
          </section>
        ))}
      </div>
    </div>
  );
}

